// Patterns for text that contains numbers, names or times. Each language supplies small phrase builders.
export function makePatterns(dict, L) {
  const tr = (s) => dict[s] ?? s;
  const lower = Object.fromEntries(Object.entries(dict).map(([k, v]) => [k.toLowerCase(), v]));
  const trl = (s) => lower[s.toLowerCase()] ?? s;
  const SEC = '(Intro|Verse|Build-up|Drop|Break|Outro|Whole song)';
  const KEY = '([A-G][♯♭]?) (major|minor)';
  return [
    [/^Playlist · (\d+) tracks$/, (_, n) => L.playlistTracks(n)],
    [/^(\d+) tracks$/, (_, n) => L.tracks(n)],
    [/^(\d+) of (\d+) songs from your list found on SoundCloud\.$/, (_, a, b) => L.foundOf(a, b)],
    [/^Recommended for you · (.+)$/, (_, d) => `${L.recommended} · ${d}`],
    [/^Curated mix · (.+)$/, (_, d) => `${L.curatedMix} · ${d}`],
    [new RegExp(`^${SEC} \\((\\d+:\\d+)\\)$`), (_, s, t) => `${tr(s)} (${t})`],
    [new RegExp(`^${SEC} · (\\S+)–(\\S+) \\(click to select, double-click to jump\\)$`), (_, s, a, b) => `${tr(s)} · ${a}–${b}${L.clickSection}`],
    [/^Jump to (.+)$/, (_, s) => L.jumpTo(tr(s))],
    [/^Only the (.+)$/, (_, s) => L.onlyThe(tr(s))],
    [/^Musical key \(Camelot (\w+)\)$/, (_, c) => `${L.musicalKey} (Camelot ${c})`],
    [new RegExp(`^${KEY}$`), (_, n, m) => L.key(n, m)],
    [new RegExp(`^· (\\d+) BPM · ${KEY}$`), (_, b, n, m) => `· ${b} BPM · ${L.key(n, m)}`],
    [new RegExp(`^· 🔑 ${KEY} \\((\\w+)\\)$`), (_, n, m, c) => `· 🔑 ${L.key(n, m)} (${c})`],
    [/^([↑↓]) (\d+) steps?( \(one part\))?$/, (_, a, n, one) => `${a} ${L.steps(n)}${one ? L.onePart : ''}`],
    [/^Repeat: (off|all|one)$/, (_, m) => L.repeat(m)],
    [/^Fine-tuning the pitch… (\d+)%$/, (_, p) => `${tr('Fine-tuning the pitch…')} ${p}%`],
    [/^Matching song B to song A… (\d+)%$/, (_, p) => `${tr('Matching song B to song A…')} ${p}%`],
    [/^Splitting the song into parts… (\d+)%$/, (_, p) => `${tr('Splitting the song into parts…')} ${p}%`],
    [/^Playing (\d+) notes on (.+)…$/, (_, n, i) => L.playingNotes(n, trl(i))],
    [/^Saving (.+)…$/, (_, x) => L.saving(tr(x))],
    [/^Couldn't play “(.+)” — skipping$/, (_, x) => L.couldntPlay(x)],
    [/^Start deck (A|B) and load deck (A|B) first$/, (_, a, b) => L.startDeck(a, b)],
    [/^\+ Load a song on deck (A|B)$/, (_, d) => `+ ${L.loadDeck(d)}`],
    [/^Load a song on deck (A|B)$/, (_, d) => L.loadDeck(d)],
    [/^Cut the (highs|mids|lows)$/, (_, b) => L.cut(b)],
    [/^([+-]?\d+) beats?$/, (_, n) => L.beats(n)],
    [/^⬇ (\d+) of (\d+) saved on this PC \(([\d.]+) MB\)(?: · saving (\d+) more…)?(?: · (\d+) couldn't be saved, will retry)?$/,
      (_, a, b, mb, more, fail) => `⬇ ${L.savedOn(a, b, mb)}${more ? ` · ${L.savingMore(more)}` : ''}${fail ? ` · ${L.failedRetry(fail)}` : ''}`],
    [/^([\s\S]*?)The AI is separating vocals, drums, bass, guitar, piano and other sounds(?: on your (.+?))?\.(?: About (\d+)s left\.)? This only happens once per song\.$/,
      (_, note, dev, eta) => `${note ? tr(note.trim()) + ' ' : ''}${L.separating(dev ? tr(dev) : '')}${eta ? L.etaLeft(eta) : ''}${L.oncePerSong}`],
    [/^✓ (.+) replied “(.*)” in ([\d.]+)s$/, (_, p, r, s) => `✓ ${L.replied(p, r, s)}`],
    [/^Asking (.+) for a search plan…$/, (_, x) => L.askingPlan(x)],
    [/^Plan: “(.+)” — searching (\d+) queries$/, (_, t, n) => L.planSearching(t, n)],
    [/^“(.+)” → (\d+) tracks$/, (_, q, n) => `“${q}” → ${L.tracks(n)}`],
    [/^Curating (\d+) from (\d+) candidates…$/, (_, a, b) => L.curatingFrom(a, b)],
    [/^Created “(.+)” with (\d+) tracks$/, (_, t, n) => L.created(t, n)],
    [/^Searching (\d+) related queries…$/, (_, n) => L.searchingRelated(n)],
    [/^For You updated with (\d+) tracks$/, (_, n) => L.forYouUpdated(n)],
    [/^Asking (.+) to pick (\d+)…$/, (_, x, n) => L.askingPick(x, n)],
    [/^(AI runtime \((.+?)\)|Song-splitting model): (\d+)%(?: of (\d+) MB)?$/, (_, what, pkg, p, mb) => `${pkg ? `${L.aiRuntime} (${pkg})` : tr('Song-splitting model')}: ${p}%${mb ? L.ofMB(mb) : ''}`],
    [new RegExp(`^Tempo (\\d+) vs (\\d+) BPM( → matched)? · Key ${KEY} vs ${KEY}(?: → song B moved (up|down) (\\d+))?$`),
      (_, a, b, matched, n1, m1, n2, m2, dir, k) => L.fitLine(a, b, !!matched, L.key(n1, m1), L.key(n2, m2), dir, k)],
    [/^Download failed: (.+)\. Check your internet connection \(or proxy\) and try again\.$/, (_, e) => L.downloadFailed(e)],
    [/^OpenAI-compatible API \((.+)\)$/, (_, x) => `${tr('OpenAI-compatible API')} (${x})`],
    [/^Anthropic API \((.+)\)$/, (_, x) => `${tr('Anthropic API')} (${x})`],
    [/^Claude CLI \((.+)\)$/, (_, x) => `${tr('Claude CLI')} (${x})`],
    [/^Custom API \((.+)\)$/, (_, x) => `${tr('Custom API')} (${x})`],
    [/^Added to “(.+)”$/, (_, x) => L.addedTo(x)],
    [/^Already in “(.+)”$/, (_, x) => L.alreadyIn(x)],
    [/^Created playlist “(.+)”$/, (_, x) => L.createdPlaylist(x)],
    [/^Skipped (\d+) unavailable songs$/, (_, n) => L.skippedN(n)],
    [/^Measured: (\d+) ms$/, (_, n) => L.measured(n)],
    [/^Removed “(.+)”$/, (_, x) => L.removed(tr(x))],
    // "Name: description" toasts (recipes, part errors) when both halves are known
    [/^([^:]{2,40}): (.+)$/, (all, a, b) => (dict[a] && dict[b] ? `${dict[a]}${L.colon}${dict[b]}` : dict[a] ? `${dict[a]}${L.colon}${b}` : all)],
  ];
}
